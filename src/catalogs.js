const text = (key, label, extra = {}) => ({ key, label, type: 'text', required: true, ...extra });
const opt = (key, label, options, extra = {}) => ({ key, label, type: 'select', options, required: true, ...extra });

function simpleNameCatalog(title, subtitle, collectionName, icon, accent, seed, extraFields = []) {
  return {
    title,
    subtitle,
    collectionName,
    icon,
    accent,
    fields: [text('name', 'Name'), ...extraFields, opt('status', 'Status', ['Active', 'Inactive'], { default: 'Active' })],
    seed,
  };
}

