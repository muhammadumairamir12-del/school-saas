function titleFromId(id) {
  return String(id || 'Module')
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

export function getModulePage(id) {
  if (MODULE_PAGES[id]) return MODULE_PAGES[id];
  const title = titleFromId(id);
  return {
    title,
    subtitle: `${title} — SkyEagle EMS workspace`,
    columns: ['Ref', 'Name', 'Class / Dept', 'Date', 'Amount', 'Status'],
    rows: rows(8, (i) => ({
      id: `${id}-${i}`,
      Ref: `${String(id).slice(0, 3).toUpperCase()}-${1000 + i}`,
      Name: `Record ${i}`,
      'Class / Dept': ['Nursery', 'Class 5', 'Class 10', 'Accounts', 'HR'][i % 5],
      Date: `2026-09-${(i % 28) + 1}`,
      Amount: money(1500 * i),
      Status: ['Open', 'Done', 'Pending', 'Active'][i % 4],
    })),
    actions: ['Add new', 'Export', 'Open report'],
    filters: ['From', 'To', 'Status'],
  };
}
